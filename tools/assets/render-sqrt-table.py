#!/usr/bin/env python3
"""Freeze the renderer's original binary32 square-root seeds in flash."""
import argparse
import math
from pathlib import Path
import struct

TARGET = Path(__file__).resolve().parents[2] / 'firmware/main/render_sqrt_table.h'

def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]

def contents():
    seeds = [min(65535, int(f32(f32(f32(math.sqrt(i)) * 2048) + .5))) for i in range(1025)]
    lines = ['// Generated by tools/assets/render-sqrt-table.py; checked against the original C arithmetic.',
             '#pragma once', '#include <stdint.h>', 'static const uint16_t s_sqrt_t[1025] = {']
    lines += ['    ' + ', '.join(map(str, seeds[i:i + 16])) + ',' for i in range(0, len(seeds), 16)]
    return '\n'.join([*lines, '};', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = contents()
    if args.check:
        if TARGET.read_text() != text:
            raise SystemExit('Renderer square-root table is stale; regenerate it')
    else:
        TARGET.write_text(text)

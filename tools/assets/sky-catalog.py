#!/usr/bin/env python3
"""Project measured J2000 stars once; firmware stores only fixed chart geometry and input routes."""
import argparse
import json
import math
import os
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tools/assets/data/skies.json'
TARGET = ROOT / 'firmware/main/tess_sky_catalog.h'


def project(stars):
    coords = [(math.radians(s['ra']), math.radians(s['dec'])) for s in stars]
    vector = [sum(v) for v in zip(*[(math.cos(d)*math.cos(a), math.cos(d)*math.sin(a), math.sin(d)) for a,d in coords])]
    ra = math.atan2(vector[1], vector[0])
    dec = math.atan2(vector[2], math.hypot(vector[0], vector[1]))
    points = []
    for a,d in coords:
        cosine = math.cos(d)*math.cos(a-ra)
        depth = math.sin(dec)*math.sin(d)+math.cos(dec)*cosine
        assert depth > .5, 'A chart must fit one tangent plane'
        points.append((-math.cos(d)*math.sin(a-ra)/depth,
                       -(math.cos(dec)*math.sin(d)-math.sin(dec)*cosine)/depth))
    low = [min(p[i] for p in points) for i in (0,1)]
    high = [max(p[i] for p in points) for i in (0,1)]
    scale = 312/max(high[i]-low[i] for i in (0,1))
    return [[round(240+(p[i]-(low[i]+high[i])/2)*scale) for i in (0,1)] for p in points]


def generate(data):
    lines = ['// Generated by tools/assets/sky-catalog.py; edit tools/assets/data/skies.json.',
             '// Coordinate database adaptation: ODbL-1.0; see NOTICE and licenses/ODbL-1.0-SIMBAD.txt.',
             '// Original tangent-plane projection of CDS SIMBAD coordinates; conventional bright-star outlines.',
             '// No chart artwork is copied. Routes are normal finger/tilt input, verified with the real physics.',
             'static const chart_t k_charts[SKY_CHARTS] = {']
    assert len(data['constellations']) == 8
    last = 0
    for c in data['constellations']:
        n = len(c['stars'])
        assert last <= n <= 7 and n >= 3
        assert c['name'].isascii() and len(c['edges']) <= 8 and 0 <= c['holes'] <= 2
        points = project(c['stars'])
        for x,y in points: assert 84 <= x <= 396 and 84 <= y <= 396
        for a,b in c['edges']: assert 0 <= a < n and 0 <= b < n and a != b
        stars = []
        magnitudes = [star['vmag'] for star in c['stars']]
        faintest, brightest = max(magnitudes), min(magnitudes)
        for (x,y), star in zip(points,c['stars']):
            magnitude = star['vmag']
            assert -2 < magnitude < 8
            # Chart-relative apparent brightness: optical size -40% to +65%, not stellar diameter.
            size = round(-40 + 105 * (faintest-magnitude) / max(1, faintest-brightest))
            stars.append(f'{{{x},{y},{size}}}')
        edges = ','.join(f'{{{a},{b}}}' for a,b in c['edges'])
        lines += [f'    {{"{c["name"]}",{n},{len(c["edges"])},{c["holes"]},',
                  '     {'+','.join(stars)+'},', '     {'+edges+'}},']
        last = n
    return '\n'.join(lines+['};',*format_routes(data),''])


def format_routes(data):
    lines=['static const int8_t k_route[SKY_CHARTS][SKY_STARS][SKY_STARS][4] = {']
    for c in data['constellations']:
        n=len(c['stars']); assert len(c['routes'])==n
        for row in c['routes']:
            assert len(row)==n
            for gx,gy,ox,oy in row: assert gx*gx+gy*gy<=16 and abs(ox)+abs(oy)<=40
        lines.append('    '+json.dumps(c['routes'],separators=(',',':')).replace('[','{').replace(']','}')+',')
    return lines+['};']



def refresh_routes(data):
    with tempfile.TemporaryDirectory(prefix='kubik-sky-routes-') as tmp:
        exe=str(Path(tmp)/'routes')
        subprocess.run([os.environ.get('CC','cc'),'-O3','-Ifirmware/main','tools/assets/sky-routes.c',
                        'firmware/main/tess_sky_stream.c','firmware/main/tess_sky_compose.c',
                        'firmware/main/tess_sky_plan.c','-lm','-o',exe],cwd=ROOT,check=True)
        routes=json.loads(subprocess.check_output([exe],cwd=ROOT))
    for c,route in zip(data['constellations'],routes): c['routes']=route
    lines=['{']+[f'  {json.dumps(k)}: {json.dumps(v)},' for k,v in data.items() if k!='constellations']
    lines.append('  "constellations": [')
    for n,c in enumerate(data['constellations']):
        lines.append('    {"name": '+json.dumps(c['name'])+', "holes": '+str(c['holes'])+',')
        lines.append('     "stars": [')
        lines.extend('       '+json.dumps(star)+(',' if i+1<len(c['stars']) else '') for i,star in enumerate(c['stars']))
        lines.append('     ], "edges": '+json.dumps(c['edges'])+', "routes": [')
        lines.extend('       '+json.dumps(row)+(',' if i+1<len(c['routes']) else '') for i,row in enumerate(c['routes']))
        lines.append('     ]}'+(',' if n+1<len(data['constellations']) else ''))
    SOURCE.write_text('\n'.join(lines+['  ]','}'])+'\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group()
    mode.add_argument('--check',action='store_true')
    mode.add_argument('--refresh-routes',action='store_true',help='recalculate diagnostic input after physics changes')
    args = parser.parse_args()
    data=json.loads(SOURCE.read_text())
    if args.refresh_routes: refresh_routes(data)
    result = generate(data)
    if args.check:
        assert TARGET.read_text() == result, 'Stale Skies catalog: run tools/assets/sky-catalog.py'
    else:
        TARGET.write_text(result)
    print('Skies catalog: 8 measured charts, uniform projection, bounded links/tilt and generated header verified')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Freeze byte-decoded scatter material, preserving C6 and native float rounding."""
import argparse
import ctypes
import ctypes.util
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
LIB = ctypes.CDLL(ctypes.util.find_library('m'))
FMA = LIB.fmaf
FMA.argtypes = [ctypes.c_float] * 3
FMA.restype = ctypes.c_float

def parameter(filename, name):
    source = (ROOT / 'firmware/main' / filename).read_text()
    match = re.search(r'^#define ' + re.escape(name) + r' ([0-9.]+)f\b', source, re.M)
    if not match:
        raise ValueError(f'Expected a literal float for {name}')
    return float(match[1])

TIMING = {name: parameter('tess_scatter.c', name) for name in ['OUT_LAG_S','OUT_S','STRUGGLE_S','RETURN_LAG_S']}
PI = parameter('tess_internal.h', 'PI')

def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]

def literal(value):
    mantissa, exponent = float(value).hex().split('p')
    return mantissa.rstrip('0').rstrip('.') + 'p' + exponent + 'f'

def material(index, fused):
    q = f32(index * f32(1 / 255))
    def add(a, b):
        return FMA(f32(a), q, f32(b)) if fused else f32(f32(f32(a) * q) + f32(b))
    struggle_to = f32(f32(f32(TIMING['OUT_LAG_S']) + f32(TIMING['OUT_S'])) + f32(TIMING['STRUGGLE_S']))
    return [f32(f32(.12) * q), add(.32, .38), f32(f32(q - f32(.5)) * f32(.9)),
            add(TIMING['RETURN_LAG_S'], struggle_to), add(.5, .7), f32(f32(2 * f32(PI)) * add(.75, 1.5)),
            add(.6, .7), add(.8, .2)]

def contents(fused):
    lines = ['// Generated by tools/assets/scatter-material-table.py; verified by the C arithmetic oracle.',
             'static const scatter_material_t k_scatter_material[256] = {']
    lines += ['    {' + ', '.join(map(literal, material(i, fused))) + '},' for i in range(256)]
    return '\n'.join([*lines, '};', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for fused in (False, True):
        path = ROOT / f"firmware/main/tess_scatter_material_{'fma' if fused else 'plain'}.h"
        text = contents(fused)
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f'Stale scatter material table: {path.name}')
        else:
            path.write_text(text)

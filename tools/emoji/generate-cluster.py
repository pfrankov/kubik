#!/usr/bin/env python3
"""Generate the screen/printer emoji-start classifier from pinned Unicode data."""
import argparse
from pathlib import Path
from atlas import pinned_sequences, UNICODE_SHA256, UNICODE_URL

ROOT = Path(__file__).resolve().parents[2]


def ranges(points):
    result = []
    for point in sorted(set(points)):
        if result and result[-1][1] + 1 == point:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def generate(data):
    # ASCII #/*/digits are emoji only as complete keycaps, handled by the scanner.
    points = {ord(sequence[0]) for sequence in pinned_sequences(data) if ord(sequence[0]) > 127}
    lines = ['// Generated by tools/emoji/generate-cluster.py; do not edit.',
             '// Unicode 17.0 emoji-test.txt, copyright 2025 Unicode, Inc.',
             '// Terms: licenses/Unicode-3.0.txt', '// Source: ' + UNICODE_URL,
             '// SHA-256: ' + UNICODE_SHA256]
    lines += [f'    {{0x{first:x}, 0x{last:x}}},' for first, last in ranges(points)]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Pinned official emoji-test-17.0.txt')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'firmware/main/emoji_cluster_data.inc'
    expected = generate(args.source.read_bytes())
    if args.check:
        if target.read_text() != expected:
            raise ValueError('Emoji-start classifier differs from the pinned Unicode data')
    else:
        target.write_text(expected)
    print(f'Emoji classifier: {len(expected.splitlines()) - 5} exact Unicode start ranges')


if __name__ == '__main__':
    main()
